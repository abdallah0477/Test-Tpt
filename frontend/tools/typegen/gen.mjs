// Generates frontend/src/api/schema.d.ts from the backend's OpenAPI schema.
// Usage: npm run gen:types            (default http://127.0.0.1:8000/openapi.json)
//        OPENAPI_URL=http://host:8000/openapi.json npm run gen:types
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const url = process.env.OPENAPI_URL ?? 'http://127.0.0.1:8000/openapi.json'
const out = fileURLToPath(new URL('../../src/api/schema.d.ts', import.meta.url))

const ast = await openapiTS(new URL(url))
const header = `// Generated by \`npm run gen:types\` from ${url}. Do not edit by hand.\n\n`
await writeFile(out, header + astToString(ast))
console.log(`wrote ${out}`)
